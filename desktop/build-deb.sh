#!/usr/bin/env bash
# Build the boringfunnels Ubuntu desktop package (.deb).
#
# Usage:
#   desktop/build-deb.sh [repo-root]
#
# Environment:
#   ELECTRON_VERSION  Electron release to bundle (default 44.9.0)
#   WORK              staging directory (default /tmp/bf-deb-work; ~1.5 GB free needed)
#   HARDLINK=1        hardlink node_modules from the repo instead of copying
#                     (much faster, requires WORK on the same filesystem)
#
# Requires: curl, unzip, dpkg-deb, node, python3+Pillow (only if icons are
# missing), and a production build (.next) in the repo (bun run build).
set -euo pipefail

REPO_ROOT="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
REPO_ROOT="$(cd "$REPO_ROOT" && pwd)"
ELECTRON_VERSION="${ELECTRON_VERSION:-44.9.0}"
WORK="${WORK:-/tmp/bf-deb-work}"
HARDLINK="${HARDLINK:-0}"
PKG="boringfunnels-desktop"
DEB_DIR="$WORK/stage"
DOWNLOADS="$WORK/downloads"

for tool in curl unzip dpkg-deb node; do
  command -v "$tool" >/dev/null 2>&1 || { echo "missing tool: $tool" >&2; exit 1; }
done

VERSION="$(sed -n 's/^Version: *//p' "$REPO_ROOT/desktop/control" | head -1 | tr -d '[:space:]')"
[ -n "$VERSION" ] || { echo "cannot read Version from desktop/control" >&2; exit 1; }

[ -d "$REPO_ROOT/.next" ] || { echo "no .next in $REPO_ROOT — run 'bun run build' first" >&2; exit 1; }
[ -x "$REPO_ROOT/node_modules/next/dist/bin/next" ] || { echo "next is not installed in $REPO_ROOT" >&2; exit 1; }

if [ ! -f "$REPO_ROOT/desktop/icons/boringfunnels-512.png" ]; then
  echo "icons missing — generating via make-icons.py"
  (cd "$REPO_ROOT/desktop" && python3 make-icons.py)
fi

rm -rf "$DEB_DIR"
mkdir -p \
  "$DEB_DIR/opt/$PKG/electron" \
  "$DEB_DIR/opt/$PKG/resources/app" \
  "$DEB_DIR/opt/$PKG/app" \
  "$DEB_DIR/DEBIAN" \
  "$DEB_DIR/usr/bin" \
  "$DEB_DIR/usr/share/applications" \
  "$DOWNLOADS"

# 1. Electron runtime
ZIP="$DOWNLOADS/electron-v${ELECTRON_VERSION}-linux-x64.zip"
if [ ! -f "$ZIP" ]; then
  echo "Downloading Electron v${ELECTRON_VERSION} (linux-x64)..."
  curl -fL --retry 3 -o "$ZIP" \
    "https://github.com/electron/electron/releases/download/v${ELECTRON_VERSION}/electron-v${ELECTRON_VERSION}-linux-x64.zip"
fi
unzip -q -o "$ZIP" -d "$DEB_DIR/opt/$PKG/electron"
chmod 4755 "$DEB_DIR/opt/$PKG/electron/chrome-sandbox" || true

# 2. The Next.js application (production tree)
cp -a "$REPO_ROOT/.next" "$DEB_DIR/opt/$PKG/app/.next"
cp -a "$REPO_ROOT/public" "$DEB_DIR/opt/$PKG/app/public"

# Ship a plain-JS config and a dependency-only package.json. A TS config
# would make 'next start' transpile next.config.ts at runtime — dragging
# typescript (and Next's package-manager self-heal) into the installed tree.
if ! grep -Eq 'reactStrictMode: *true' "$REPO_ROOT/next.config.ts"; then
  echo "WARNING: next.config.ts deviates from the simple template —" >&2
  echo "         review the generated next.config.js below." >&2
fi
printf '%s\n' \
  '// generated by desktop/build-deb.sh — keep in sync with next.config.ts' \
  '// (a JS config keeps typescript out of the runtime tree)' \
  'module.exports = { reactStrictMode: true };' \
  > "$DEB_DIR/opt/$PKG/app/next.config.js"
node -e '
  const fs = require("fs");
  const p = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
  delete p.devDependencies;
  p.scripts = { start: "next start" };
  fs.writeFileSync(process.argv[2], JSON.stringify(p, null, 2) + "\n");
' "$REPO_ROOT/package.json" "$DEB_DIR/opt/$PKG/app/package.json"
if [ "$HARDLINK" = "1" ]; then
  cp -al "$REPO_ROOT/node_modules" "$DEB_DIR/opt/$PKG/app/node_modules"
else
  echo "Copying node_modules (the slow step)..."
  cp -a "$REPO_ROOT/node_modules" "$DEB_DIR/opt/$PKG/app/node_modules"
fi

# Prune packages that only the BUILD uses. Next 16 declares @swc/helpers,
# baseline-browser-mapping, caniuse-lite and postcss as RUNTIME dependencies
# (they are hoisted top-level), so nothing in next's dependency closure may
# be removed — only the tailwind/toolchain and type-only packages.
(
  cd "$DEB_DIR/opt/$PKG/app/node_modules"
  rm -rf -- \
    typescript @types tailwindcss @tailwindcss @alloc \
    lightningcss lightningcss-linux-x64-gnu lightningcss-linux-x64-musl \
    detect-libc csstype magic-string .bin 2>/dev/null || true
)

# The production server writes its cache at runtime — make it writable for
# any local user (the tree itself is root-owned after installation).
mkdir -p "$DEB_DIR/opt/$PKG/app/.next/cache"
find "$DEB_DIR/opt/$PKG/app/.next/cache" -type d -exec chmod a+rwX {} + 2>/dev/null || true
find "$DEB_DIR/opt/$PKG/app/.next/cache" -type f -exec chmod a+rw {} + 2>/dev/null || true

# 3. Electron app sources
cp -a "$REPO_ROOT/desktop/main.js" \
      "$REPO_ROOT/desktop/preload.js" \
      "$DEB_DIR/opt/$PKG/resources/app/"
cp -a "$REPO_ROOT/desktop/icons" "$DEB_DIR/opt/$PKG/resources/app/icons"
sed -e "s/@VERSION@/$VERSION/" "$REPO_ROOT/desktop/resources-app.package.json" \
  > "$DEB_DIR/opt/$PKG/resources/app/package.json"

# 4. System integration
install -m 755 "$REPO_ROOT/desktop/wrapper" "$DEB_DIR/usr/bin/boringfunnels"
install -m 644 "$REPO_ROOT/desktop/boringfunnels.desktop" \
  "$DEB_DIR/usr/share/applications/boringfunnels.desktop"
for size in 16 32 48 64 128 256 512; do
  install -D -m 644 "$REPO_ROOT/desktop/icons/boringfunnels-$size.png" \
    "$DEB_DIR/usr/share/icons/hicolor/${size}x${size}/apps/boringfunnels.png"
done

# 5. Debian control
cp -a "$REPO_ROOT/desktop/control" "$DEB_DIR/DEBIAN/control"
for s in postinst prerm postrm; do
  install -m 755 "$REPO_ROOT/desktop/$s" "$DEB_DIR/DEBIAN/$s"
done

# 6. Assemble
echo "Packing .deb (xz)..."
dpkg-deb --root-owner-group -Zxz --build "$DEB_DIR" "$WORK/${PKG}_${VERSION}_amd64.deb"
(
  cd "$WORK"
  sha256sum "${PKG}_${VERSION}_amd64.deb" > "${PKG}_${VERSION}_amd64.deb.sha256"
)

echo
echo "Built: $WORK/${PKG}_${VERSION}_amd64.deb"
du -h "$WORK/${PKG}_${VERSION}_amd64.deb"
